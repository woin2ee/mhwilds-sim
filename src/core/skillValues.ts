/** 수치 한 줄: 화면에서 표의 한 줄(레벨이 열) */
export interface ValueRow {
  /** 무엇이 바뀌는지 (게임 효과 글의 낱말: 속성 공격치·기초 공격력·회심률 …) */
  label: string
  /** 레벨(시리즈·그룹 스킬은 단계)마다의 값. values[0] 이 Lv1·첫 단계, 빈 글은 그 레벨에 없는 값 */
  values: readonly string[]
  /** 무기 종류에 따라 다른 값. values 는 여기에 없는 무기 종류의 값 */
  weapons?: readonly WeaponValues[]
}

export interface WeaponValues {
  kinds: readonly WeaponKind[]
  values: readonly string[]
}

export interface SkillValues {
  rows?: readonly ValueRow[]
  /** 레벨과 상관없는 것: 효과 시간·재발동 대기·발동 조건 */
  notes?: readonly string[]
  /** 출처마다 다르거나 확실하지 않은 점 */
  caveats?: readonly string[]
}

/** 표의 한 줄. 무기 종류에 따라 다르면 [무기 종류들, 레벨마다의 값] 을 뒤에 붙인다 */
function row(label: string, values: readonly string[], ...weapons: [readonly WeaponKind[], readonly string[]][]): ValueRow {
  if (weapons.length === 0) return { label, values }
  return { label, values, weapons: weapons.map(([kinds, v]) => ({ kinds, values: v })) }
}

/** 한 레벨(단계)짜리 스킬의 줄 */
const one = (label: string, value: string) => row(label, [value])

