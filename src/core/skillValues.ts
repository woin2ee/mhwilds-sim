export const SKILL_VALUES: ReadonlyMap<number, SkillValues> = new Map(SKILL_VALUE_LIST)

export function skillValues(gameId: number): SkillValues | undefined {
  return SKILL_VALUES.get(gameId)
}

/** 그 무기 종류에서의 레벨 값 (level 은 1 부터) */
export function rowValue(row: ValueRow, level: number, kind: WeaponKind): string {
  const group = row.weapons?.find((w) => w.kinds.includes(kind))
  return (group ?? row).values[level - 1] ?? ''
}

/** 표의 열 수 (가장 긴 줄) */
export function valueColumns(values: SkillValues): number {
  return Math.max(0, ...(values.rows ?? []).map((r) => r.values.length))
}
